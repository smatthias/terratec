import {exportJobBackup,validateJobBackup} from '../shared/job-backup.mjs';
import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {jobStore} from './job-store.mjs';
import {validateProject} from '../shared/project.mjs';
const base=validateProject({schemaVersion:1,units:'m',name:'Source',room:{width:6,depth:4,height:3}});
const project=validateProject({...base,room:{...base.room,furniture:[{id:'a',name:'Cabinet',type:'cabinet',width:.9,height:1.2,depth:.5,thickness:.018,shelves:1,x:0,z:0,rotation:0}]}});
test('fulfilment is revision-bound, validates transitions, preserves audit and rejects stale tracking',async t=>{
  const directory=await mkdtemp(join(tmpdir(),'terratec-fulfilment-'));t.after(()=>rm(directory,{recursive:true,force:true}));const store=jobStore(directory);
  const record=await store.create({name:'Kitchen',project}),id=record.id;
  const input={revision:1,expectedRevision:1,expectedEvent:0,status:'assigned',workshop:'Berlin shop',dueDate:'2026-12-01',actor:'Matthias',note:'Workshop planning'};
  await assert.rejects(()=>store.fulfil(id,input),/reviewed/);
  await store.review(id,{revision:1,expectedRevision:1,reviewer:'M',note:'Reviewed'});
  await assert.rejects(()=>store.fulfil(id,{...input,dueDate:'2026-02-30'}),/due date/);
  await assert.rejects(()=>store.fulfil(id,{...input,actor:''}),/actor/);
  const assigned=await store.fulfil(id,input);assert.equal(assigned.revisions[0].fulfilment.status,'assigned');
  await assert.rejects(()=>store.revise(id,{expectedRevision:1,project:{...project,name:'Changed'}}),/active/);
  await assert.rejects(()=>store.fulfil(id,input),/changed/);
  await assert.rejects(()=>store.fulfil(id,{...input,status:'completed',expectedEvent:1}),/transition/);
  const outcomes=await Promise.allSettled([store.fulfil(id,{...input,status:'in-production',expectedEvent:1}),store.fulfil(id,{...input,status:'in-production',expectedEvent:1})]);assert.equal(outcomes.filter(r=>r.status==='fulfilled').length,1);
  const completed=await store.fulfil(id,{...input,status:'completed',expectedEvent:2});
  assert.deepEqual(completed.revisions[0].fulfilment.events.map(e=>e.status),['assigned','in-production','completed']);
  await assert.rejects(()=>store.fulfil(id,{...input,status:'cancelled',expectedEvent:3}),/transition/);
  const revised=await store.revise(id,{expectedRevision:1,project:{...project,name:'Changed'}});
  assert.equal(revised.revisions[1].status,'planned');assert.equal(revised.revisions[1].fulfilment,undefined);
  assert.deepEqual(revised.revisions[0].manifest,record.revisions[0].manifest);
  const persisted=await jobStore(directory).read(id);assert.equal(persisted.revisions[0].fulfilment.events.length,3);
  assert.deepEqual(await validateJobBackup(JSON.parse(await exportJobBackup(persisted))),persisted);
  const forged=structuredClone(persisted);forged.revisions[0].fulfilment.events[1].status='completed';
  await assert.rejects(async()=>validateJobBackup(JSON.parse(await exportJobBackup(forged))),/tracking/);
  await store.review(id,{revision:2,expectedRevision:2,reviewer:'M',note:'Reviewed again'});
  await store.fulfil(id,{...input,revision:2,expectedRevision:2});
  const cancelled=await store.fulfil(id,{...input,revision:2,expectedRevision:2,expectedEvent:1,status:'cancelled'});assert.equal(cancelled.revisions[1].fulfilment.status,'cancelled');
});
