import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {makeServer} from './index.mjs';
const project={schemaVersion:1,units:'m',name:'First',room:{width:6,depth:4,height:3}};
test('project API isolates projects, lists renames, persists across restart and rejects invalid IDs',async t=>{
  const dataDir=await mkdtemp(join(tmpdir(),'terratec-projects-'));let server,base;
  const start=async()=>{server=makeServer({dataDir});await new Promise(r=>server.listen(0,'127.0.0.1',r));base='http://127.0.0.1:'+server.address().port;};
  const stop=()=>new Promise(r=>server.close(r));
  t.after(async()=>{if(server.listening)await stop();await rm(dataDir,{recursive:true,force:true});});
  await start();
  const send=(path,method,value)=>fetch(base+path,{method,headers:{'content-type':'application/json'},body:JSON.stringify(value)});
  assert.deepEqual(await (await fetch(base+'/api/projects')).json(),[]);
  const first=await (await send('/api/projects','POST',project)).json();
  const second=await (await send('/api/projects','POST',{...project,name:'Second'})).json();
  assert.notEqual(first.id,second.id);
  const updated={...first.project,name:'Renamed',room:{...first.project.room,height:4}};
  assert.equal((await send('/api/projects/'+first.id,'PUT',updated)).status,200);
  assert.equal((await send('/api/projects/'+first.id,'PUT',{...updated,units:'ft'})).status,400);
  assert.equal((await fetch(base+'/api/projects/not-an-id')).status,400);
  assert.equal((await fetch(base+'/api/projects/00000000-0000-0000-0000-000000000000')).status,404);
  await stop();await start();
  assert.equal((await (await fetch(base+'/api/projects/'+first.id)).json()).project.room.height,4);
  assert.equal((await (await fetch(base+'/api/projects/'+second.id)).json()).project.room.height,3);
  const list=await (await fetch(base+'/api/projects')).json();
  assert.deepEqual(list.map(p=>p.name).sort(),['Renamed','Second']);
});
